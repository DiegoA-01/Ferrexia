-- Roles: los de siempre son plantillas del sistema (empresa_id NULL, de solo lectura). Los roles propios de cada
-- empresa (Parte B) llevarán su empresa_id.
ALTER TABLE rol
    ADD COLUMN empresa_id BIGINT NULL AFTER id,
    ADD COLUMN es_plantilla BOOLEAN NOT NULL DEFAULT FALSE AFTER descripcion,
    ADD CONSTRAINT fk_rol_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id);
UPDATE rol SET es_plantilla = TRUE WHERE empresa_id IS NULL;

