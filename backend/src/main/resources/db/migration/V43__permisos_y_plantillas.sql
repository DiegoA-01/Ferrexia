-- Permisos sueltos de una persona: concedido = TRUE suma un permiso que su rol no da, FALSE quita uno que sí da.
CREATE TABLE usuario_permiso (
    usuario_id BIGINT  NOT NULL,
    permiso_id BIGINT  NOT NULL,
    empresa_id BIGINT  NOT NULL,
    concedido  BOOLEAN NOT NULL,
    creado_en  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, permiso_id),
    INDEX idx_usuario_permiso_empresa (empresa_id),
    CONSTRAINT fk_usuario_permiso_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_usuario_permiso_permiso FOREIGN KEY (permiso_id) REFERENCES permiso(id),
    CONSTRAINT fk_usuario_permiso_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id)
) ENGINE=InnoDB;
